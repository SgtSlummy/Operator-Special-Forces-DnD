def finish(obj,name,mat):
 obj.name=name;obj.data.materials.append(mat);return obj

def box(name,pos,size,mat=stone,bevel=.035):
 bpy.ops.mesh.primitive_cube_add(size=1,location=tuple(v*F for v in pos));o=bpy.context.object;o.dimensions=tuple(v*F for v in size)
 bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
 finish(o,name,mat)
 if bevel:
  mod=o.modifiers.new('Soft worn edges','BEVEL');mod.width=bevel*F;mod.segments=3
  o.modifiers.new('Weighted normals','WEIGHTED_NORMAL')
 return o

def cylinder(name,pos,radius,depth,mat=brass,rot=(0,0,0),vertices=32):
 bpy.ops.mesh.primitive_cylinder_add(vertices=vertices,radius=radius*F,depth=depth*F,location=tuple(v*F for v in pos),rotation=rot)
 o=finish(bpy.context.object,name,mat);mod=o.modifiers.new('Machined edge','BEVEL');mod.width=.025*F;mod.segments=3
 for p in o.data.polygons:p.use_smooth=True
 return o

def tube(name,points,radius=.055,mat=brass):
 curve=bpy.data.curves.new(name,'CURVE');curve.dimensions='3D';curve.resolution_u=12;curve.bevel_depth=radius*F;curve.bevel_resolution=3
 spline=curve.splines.new('POLY');spline.points.add(len(points)-1)
 for p,v in zip(spline.points,points):p.co=(*(c*F for c in v),1)
 obj=bpy.data.objects.new(name,curve);scene.collection.objects.link(obj);obj.data.materials.append(mat);return obj

