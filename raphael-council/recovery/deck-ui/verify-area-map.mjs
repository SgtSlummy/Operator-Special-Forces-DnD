import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mountReplay } from './deck-client.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.DECK_PLAYWRIGHT_MODULE || 'playwright');
const reportRoot = resolve(process.env.RAPHAEL_PARTY_REPORT_DIR || 'tmp/party-session');
const originalSession = await readFile(join(reportRoot, 'session.json'), 'utf8');
const data = JSON.parse(originalSession);
const html = await readFile(join(reportRoot, 'deck.html'), 'utf8');
assert(data.steps.length >= 3, 'Area-map contract check needs three replay moments');
const fixture = structuredClone(data);
fixture.steps = fixture.steps.slice(0, 3);
// Existing illustrations exercise image switching in a test-only fixture, not authored geography.
const imageOne = 'images/' + data.steps[0].image.approvedImage + '.png';
const imageTwo = 'images/' + data.steps.at(-1).image.approvedImage + '.png';
fixture.steps[0].areaMap = { imageFile: imageOne, title: 'Known-location control fixture', currentLocation: data.steps[0].location.title, description: 'Test-only image reference; no rooms, distances or routes are implied.', type: 'knownlocations' };
fixture.steps[1].areaMap = { imageFile: imageTwo, title: 'Next recorded location fixture', currentLocation: data.steps.at(-1).location.title, description: 'Second test-only image reference.', type: 'knownlocations' };
fixture.steps[2].areaMap = { imageFile: 'images/area-map-missing-for-test.png', title: 'Unavailable fixture' };
delete fixture.steps[0].imageFile; // Absent field keeps compatibility with legacy exports.
fixture.steps[2].imageFile = null; // Explicit denial must not use available legacy art.
fixture.steps[2].image = { ...fixture.steps[2].image, approvedImage: data.steps[0].image.approvedImage };
// A narrative lead must not relabel the actual board or its approved scene art.
fixture.steps[1].location = { ...fixture.steps[1].location, id: 'drowned-abbey', title: 'Drowned Abbey' };
fixture.steps[1].mapScene = { title: 'Saltglass Shore' };
fixture.steps[1].imageFile = imageOne;
fixture.steps[1].sceneImageTitle = 'Saltglass Shore · Approved scene';
fixture.steps[1].image = { ...fixture.steps[1].image, approvedImage: 'unavailable-legacy-scene-for-test' };
fixture.steps[1].displayWarnings = ['Narration names Drowned Abbey; the recorded board remains Saltglass Shore.'];
const assets = new Set([imageOne, imageTwo]);
for (const step of fixture.steps) for (const path of Object.values(step.mapImages || {})) if (typeof path === 'string') assets.add(path);
for (const id of ['branna', 'pip', 'kael', 'brine']) assets.add('images/portrait-' + id + '.png');
const escJson = value => JSON.stringify(value).replace(/</g, '\\u003c');
const fixtureHtml = html.replace('<head>', '<head><base href="' + pathToFileURL(reportRoot + '/').href + '">').replace(/<script>[\s\S]*?<\/script>/, () => '<script>(' + mountReplay.toString() + ')(' + escJson(fixture) + ',' + escJson([...assets]) + ');</script>');
const artifacts = join(reportRoot, 'deck-ui-checks');
await mkdir(artifacts, { recursive: true });
const fixtureFile = join(artifacts, 'area-controls-fixture.html');
await writeFile(fixtureFile, fixtureHtml, 'utf8');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const results = [];
try {
  for (const width of [320, 736, 1024]) {
    const page = await browser.newPage({ viewport: { width, height: 800 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(fixtureFile).href);
    await page.locator('#map-image').evaluate(image => image.decode());
    assert.equal(await page.locator('#battle-map').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#scene-image').getAttribute('src'), imageOne, 'Absent imageFile permits legacy approved art');
    assert.equal(await page.locator('#area-map').isDisabled(), false);
    await page.locator('#area-map').focus();
    await page.keyboard.press('Space');
    await page.locator('#map-image').evaluate(image => image.decode());
    assert.equal(await page.locator('#area-map').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#battle-map').getAttribute('aria-pressed'), 'false');
    assert.equal(await page.locator('#map-image').getAttribute('src'), imageOne);
    assert.equal(await page.locator('#map-caption').textContent(), 'Known locations · Not to scale');
    assert.match(await page.locator('#map-image').getAttribute('alt'), /Known-location control fixture/);
    assert.match(await page.locator('#map-image').getAttribute('alt'), /Not to scale/);
    assert((await page.locator('#map-image').getAttribute('alt')).includes(fixture.steps[0].areaMap.description));
    assert(await page.locator('#map-caption').evaluate(element => element.getBoundingClientRect().height <= parseFloat(getComputedStyle(element).lineHeight) + 1), 'Area caption must fit one line');
    assert.equal(await page.locator('#battle-inspector').isVisible(), false);
    await page.locator('#enlarge-map').click();
    assert.equal(await page.locator('#enlarge-map').getAttribute('aria-expanded'), 'true');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('#enlarge-map').click();
    await page.locator('#next').click();
    await page.locator('#map-image').evaluate(image => image.decode());
    assert.equal(await page.locator('#map-image').getAttribute('src'), imageTwo);
    assert.equal(await page.locator('#map-caption').textContent(), 'Known locations · Not to scale');
    assert.match(await page.locator('#map-image').getAttribute('alt'), /Next recorded location fixture/);
    assert((await page.locator('#map-image').getAttribute('alt')).includes(fixture.steps[1].areaMap.description));
    assert.equal(await page.locator('#location-title').textContent(), 'Saltglass Shore');
    assert.equal(await page.title(), 'Saltglass Shore · Local DM replay preview');
    assert.equal(await page.locator('#scene-image').getAttribute('src'), imageOne);
    assert.equal(await page.locator('#scene-image').getAttribute('alt'), 'Illustration of ' + fixture.steps[1].sceneImageTitle);
    assert.equal(await page.locator('#scene-caption').textContent(), fixture.steps[1].sceneImageTitle + ' · Scene illustration');
    assert.equal(await page.locator('#display-warnings').isVisible(), true);
    assert.equal(await page.locator('#display-warnings').textContent(), fixture.steps[1].displayWarnings[0]);
    await page.locator('#scene-image').evaluate(image => image.decode());
    await page.screenshot({ path: join(artifacts, 'caption-check-' + width + '.png'), fullPage: true });
    await page.locator('#next').click();
    assert.equal(await page.locator('#area-map').isDisabled(), true);
    assert.equal(await page.locator('#battle-map').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#map-image').getAttribute('src'), fixture.steps[2].mapImages.admin);
    assert.match(await page.locator('#area-map-status').textContent(), /supplied image is missing/);
    assert.equal(await page.locator('#scene-image').isVisible(), false, 'Explicit null must not fall back to legacy art');
    assert.equal(await page.locator('#scene-image').getAttribute('src'), null);
    assert.equal(await page.locator('#scene-image').getAttribute('alt'), null);
    assert.equal(await page.locator('#scene-missing').isVisible(), true);
    await page.locator('#previous').click();
    await page.locator('#tactical > summary').click();
    await page.locator('#viewer-select').selectOption('player');
    assert.equal(await page.locator('#area-map').isDisabled(), true);
    assert.equal(await page.locator('#map-image').getAttribute('src'), null);
    assert.equal(await page.locator('#map-link').getAttribute('href'), null);
    assert.equal(await page.locator('#map-missing').textContent(), 'Player view unavailable — visibility-scoped snapshot required');
    await page.locator('#viewer-select').selectOption('admin');
    await page.locator('#tactical > summary').click();
    assert.equal(await page.locator('#legend').count(), 0);
    const targets = await page.locator('button:visible, select:visible').evaluateAll(elements => elements.map(element => ({ name: element.textContent.trim(), height: element.getBoundingClientRect().height })));
    assert(targets.every(target => target.height >= 44), 'All controls need 44px targets');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    results.push({ width, areaSwitch: 'pass', missingArea: 'pass', stepBoundArea: 'pass', playerDenied: 'pass', targets44px: 'pass', pageErrors: errors.length });
    await page.close();
  }
  assert.equal(await readFile(join(reportRoot, 'session.json'), 'utf8'), originalSession, 'Area checks must not modify session.json');
  console.log(JSON.stringify({ areaMapContract: 'pass', results, fixtureOnly: fixtureFile, sessionUnchanged: true }, null, 2));
} finally { await browser.close(); }
